const LanguageContext = createContext<PreferredLanguage>('en');

export function I18nProvider({ language, children }: { language: PreferredLanguage; children: ReactNode }) {
  return <LanguageContext.Provider value={language}>{children}</LanguageContext.Provider>;
}

export function translate(language: PreferredLanguage, key: TranslationKey, replacements?: Replacements): string {
  const english = en[key] || String(key);
  const localized = language === 'bn' ? bn[key] : undefined;
  return (localized || english).replace(/\{(\w+)\}/g, (_match, name: string) => String(replacements?.[name] ?? ''));
}

export function formatInr(amount: number): string {
  const safeAmount = Number.isFinite(amount) ? amount : 0;
  return `₹${new Intl.NumberFormat('en-IN', { maximumFractionDigits: 2 }).format(safeAmount)}`;
}

export function useI18n() {
  const language = useContext(LanguageContext);
  const t = useCallback((key: TranslationKey, replacements?: Replacements) => translate(language, key, replacements), [language]);
  return {
    language,
    t,
    formatMoney: formatInr,
  };
}
